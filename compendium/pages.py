"""The list of sphere pages in a folder, as an index page and as the nav list every page loads.

Two outputs per folder:
  sayings-index.html  a page listing every sphere page, grouped and described;
  sayings-nav.js      window.SAYINGS_PAGES = [...], which each page's Pages menu reads.
Each page links to "sayings-nav.js" and "sayings-index.html" by relative name, so the same page
works in the website's demos folder (files named sayings-*.html; other projects' files are left
alone) and in the local export folder (sphere-*.html, compare-*.html). Because the list is loaded
when a page opens, older pages show newly published ones without being redrawn.
"""

import html
import json
import re
from datetime import datetime
from pathlib import Path

INDEX = "sayings-index.html"
NAV = "sayings-nav.js"
GROUPS = [
    ("Around a situation", "A situation at the top of the globe, with the sayings that best fit it gathered around it."),
    ("Tags vs meaning", "Two globes of the same sayings, by shared tags and by meaning, turning together."),
    ("Sayings spheres", "Sayings laid out on a globe so related ones sit together."),
]


def _meta(path):
    head = path.read_text(encoding="utf-8", errors="replace")[:4000]
    title = re.search(r"<title>(.*?)</title>", head, re.S)
    desc = re.search(r'<meta name="description" content="(.*?)">', head, re.S)
    return (html.unescape(title.group(1).strip()) if title else path.stem,
            html.unescape(desc.group(1).strip()) if desc else "")


def _number(name):
    m = re.search(r"-(\d+)\.html$", name)
    return int(m.group(1)) if m else 0


def _group(name, title):
    if title.startswith("Sayings around:"):
        return GROUPS[0][0]
    if "compare-" in name:
        return GROUPS[1][0]
    return GROUPS[2][0]


def collect(folder, prefix):
    """[{file, title, desc, group, date, size}] for the sphere pages in folder, in index order."""
    folder = Path(folder)
    files = [p for p in folder.glob(f"{prefix}*.html")
             if p.name != INDEX and re.search(r"(sphere|compare)-\d+\.html$", p.name)]
    out = []
    for p in files:
        title, desc = _meta(p)
        out.append({"file": p.name, "title": title, "desc": desc, "group": _group(p.name, title),
                    "date": datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d"),
                    "size": round(p.stat().st_size / 1e6, 1)})
    order = {g[0]: k for k, g in enumerate(GROUPS)}
    return sorted(out, key=lambda e: (order[e["group"]], -_number(e["file"]), e["file"]))


def build(folder, prefix=""):
    """Write the index page and the nav list for folder. Returns the number of pages."""
    folder = Path(folder)
    pages = collect(folder, prefix)
    nav = "/* Generated by Wise-Sayings (compendium/pages.py): the sphere pages in this folder. */\n" \
          "window.SAYINGS_PAGES = " + json.dumps(
              [{k: e[k] for k in ("file", "title", "group")} for e in pages], ensure_ascii=False, indent=1) + ";\n"
    (folder / NAV).write_text(nav, encoding="utf-8")
    (folder / INDEX).write_text(_index_html(pages), encoding="utf-8")
    return len(pages)


def _index_html(pages):
    parts = []
    for heading, intro in GROUPS:
        items = [e for e in pages if e["group"] == heading]
        if not items:
            continue
        parts.append(f"<h2>{html.escape(heading)}</h2><p class=\"intro\">{html.escape(intro)}</p><ul>")
        for e in items:
            parts.append(f'<li><a href="{html.escape(e["file"])}">{html.escape(e["title"])}</a>'
                         f'<span class="meta">{e["date"]} · {e["size"]} MB</span>'
                         + (f'<div class="desc">{html.escape(e["desc"])}</div>' if e["desc"] else "") + "</li>")
        parts.append("</ul>")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Wise Sayings: sphere pages</title>
<meta name="description" content="Index of the Wise-Sayings sphere pages.">
<!-- Generated by D:\\Projects\\Wise-Sayings (compendium/pages.py); edits here are overwritten. -->
<style>
  :root {{ --ground: #0e1116; --panel: #161b22; --line: #2a313b; --ink: #e6e1d6; --dim: #8b919a; --accent: #9db7e8; }}
  body {{ margin: 0; background: var(--ground); color: var(--ink); font: 15px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }}
  main {{ max-width: 820px; margin: 0 auto; padding: 40px 24px 60px; }}
  h1 {{ font: italic 30px Georgia, "Times New Roman", serif; margin: 0 0 6px; }}
  h2 {{ font: italic 20px Georgia, "Times New Roman", serif; margin: 34px 0 2px; }}
  .lead, .intro, .meta, footer {{ color: var(--dim); }}
  .intro {{ margin: 0 0 10px; font-size: 14px; }}
  ul {{ list-style: none; padding: 0; margin: 0; }}
  li {{ background: var(--panel); border: 1px solid var(--line); border-radius: 8px; padding: 12px 14px; margin: 8px 0; }}
  a {{ color: var(--accent); text-decoration: none; font-weight: 600; }}
  a:hover {{ text-decoration: underline; }}
  .meta {{ float: right; font-size: 12px; }}
  .desc {{ font-size: 13px; margin-top: 4px; }}
  footer {{ margin-top: 40px; font-size: 12px; }}
</style>
</head>
<body><main>
<h1>Wise Sayings: sphere pages</h1>
<p class="lead">A curated compendium of sayings (apophthegms, maxims, aphorisms, proverbs), laid out on globes so that
related sayings sit together and opposing ones face each other across the sphere. Drag to turn, click a saying for its
lens, press C for the controls. Every page has a Pages menu to move between them.</p>
{''.join(parts) or '<p>No pages published yet.</p>'}
<footer>{len(pages)} page(s) · updated {datetime.now().strftime('%Y-%m-%d %H:%M')}</footer>
</main></body>
</html>
"""
